// Converts Michroma glyph outlines into committed SVG path data for the banded
// wordmark (src/components/wordmark-data.ts) and the favicon (src/app/icon.svg).
// Run with `pnpm wordmark` after changing the font or the texts.
import opentype from 'opentype.js'
import { readFileSync, writeFileSync } from 'node:fs'

const BANDS = ['#ff4fd8', '#7b6cff', '#3ff0ff', '#8bff6b']
const ttf = readFileSync(new URL('./fonts/Michroma-Regular.ttf', import.meta.url))
const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength))

// Manual glyph layout (advance widths + pair kerning). Michroma's contextual
// substitutions aren't needed, and opentype.js can't apply them.
function textPath(text, x, y, size) {
  const scale = size / font.unitsPerEm
  const path = new opentype.Path()
  const glyphs = [...text].map(ch => font.charToGlyph(ch))
  glyphs.forEach((g, i) => {
    path.extend(g.getPath(x, y, size))
    x += g.advanceWidth * scale
    if (glyphs[i + 1]) x += font.getKerningValue(g, glyphs[i + 1]) * scale
  })
  return path
}

const out = {}
for (const text of ['kev.in', 'hi@kev.in', 'k']) {
  const bb = textPath(text, 0, 100, 100).getBoundingBox()
  const shifted = textPath(text, -bb.x1, 100 - bb.y1, 100)
  out[text] = { d: shifted.toPathData(2), width: +(bb.x2 - bb.x1).toFixed(2), height: +(bb.y2 - bb.y1).toFixed(2) }
}

writeFileSync(
  new URL('../src/components/wordmark-data.ts', import.meta.url),
  `// Generated by scripts/build-wordmark.mjs from Michroma (OFL). Do not edit.\nexport const WORDMARKS = ${JSON.stringify(out, null, 2)} as const\n`,
)

const k = out.k
const side = Math.max(k.width, k.height)
const pad = side * 0.18
const box = side + pad * 2
const ox = (side - k.width) / 2
const oy = (side - k.height) / 2
writeFileSync(
  new URL('../src/app/icon.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-pad} ${-pad} ${box} ${box}"><rect x="${-pad}" y="${-pad}" width="${box}" height="${box}" rx="${box * 0.2}" fill="#0c0b1c"/><clipPath id="kev-in-icon"><path transform="translate(${ox} ${oy})" d="${k.d}"/></clipPath><g clip-path="url(#kev-in-icon)">${BANDS.map((c, i) => `<rect x="0" y="${oy + (k.height / 4) * i}" width="${side}" height="${k.height / 4 + 0.5}" fill="${c}"/>`).join('')}</g></svg>\n`,
)

console.log(Object.fromEntries(Object.entries(out).map(([t, v]) => [t, [v.width, v.height]])))
